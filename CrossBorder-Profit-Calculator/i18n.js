const languageStorageKey = 'crossBorderProfitLanguage';
let currentLanguage = 'zh';
const textNodeKeys = new WeakMap();
const attributeKeys = new WeakMap();

function getStoredLanguage() {
  try {
    const saved = localStorage.getItem(languageStorageKey);
    return translations[saved] ? saved : 'zh';
  } catch (error) {
    return 'zh';
  }
}

function t(key, variables = {}) {
  const template = translations[currentLanguage]?.[key] ?? translations.zh[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => variables[name] ?? match);
}

function findTranslationKey(value) {
  const text = String(value).trim();
  for (const language of Object.keys(translations)) {
    const entry = Object.entries(translations[language]).find(([, translated]) => translated === text);
    if (entry) return entry[0];
  }
  return null;
}

function applyTranslations(root = document) {
  const walker = document.createTreeWalker(root.body || root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => {
    if (['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName)) return;
    const original = node.nodeValue;
    const trimmed = original.trim();
    if (!trimmed) return;
    let key = textNodeKeys.get(node);
    if (!key) {
      key = findTranslationKey(trimmed);
      if (key) textNodeKeys.set(node, key);
    }
    if (key) node.nodeValue = original.replace(trimmed, t(key));
  });

  root.querySelectorAll?.('[placeholder], [aria-label], [title]').forEach(element => {
    let bindings = attributeKeys.get(element);
    if (!bindings) {
      bindings = {};
      ['placeholder', 'aria-label', 'title'].forEach(attribute => {
        if (!element.hasAttribute(attribute)) return;
        const key = findTranslationKey(element.getAttribute(attribute));
        if (key) bindings[attribute] = key;
      });
      attributeKeys.set(element, bindings);
    }
    Object.entries(bindings).forEach(([attribute, key]) => element.setAttribute(attribute, t(key)));
  });

  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : currentLanguage;
  document.title = t('app.title');
  document.querySelectorAll('[data-language]').forEach(button => {
    const isActive = button.dataset.language === currentLanguage;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

function setLanguage(language, persist = true) {
  if (!translations[language]) return;
  currentLanguage = language;
  if (persist) {
    try { localStorage.setItem(languageStorageKey, language); } catch (error) { /* 不影响语言切换 */ }
  }
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
}

function getCurrentLanguage() {
  return currentLanguage;
}

function formatLocalizedNumber(value) {
  return Number(value).toLocaleString(currentLanguage === 'en' ? 'en-US' : 'zh-CN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function formatLocalizedCny(value) {
  return `${currentLanguage === 'en' ? 'CNY ' : ''}¥${formatLocalizedNumber(value)}`;
}

function formatLocalizedUsd(value) {
  return `${currentLanguage === 'en' ? 'USD ' : ''}$${formatLocalizedNumber(value)}`;
}

function formatLocalizedDate(date) {
  return new Intl.DateTimeFormat(currentLanguage === 'en' ? 'en-US' : 'zh-CN', currentLanguage === 'en'
    ? { year: 'numeric', month: 'short', day: 'numeric' }
    : { year: 'numeric', month: 'long', day: 'numeric' }).format(date);
}

function formatLocalizedDateTime(date) {
  return new Intl.DateTimeFormat(currentLanguage === 'en' ? 'en-US' : 'zh-CN', {
    year: 'numeric', month: currentLanguage === 'en' ? 'short' : 'long', day: 'numeric', hour: '2-digit', minute: '2-digit', hour12: false
  }).format(date);
}

if (typeof document !== 'undefined') {
  currentLanguage = getStoredLanguage();
  applyTranslations();
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  });
}

